async () => {
  const messages=[];
  const pause=()=>new Promise(r=>setTimeout(r,80));
  const check=(condition,message)=>{if(!condition)throw Error(message);messages.push('PASS '+message);};
  const click=async(selector)=>{const el=document.querySelector(selector);if(!el||el.disabled)throw Error('Not clickable: '+selector);el.click();await pause();};
  const button=async(text,root=document)=>{const el=[...root.querySelectorAll('button')].find(b=>b.textContent.startsWith(text)&&!b.disabled);if(!el)throw Error('Missing button '+text);el.click();await pause();};
  await button('Restart seed');
  check(document.querySelectorAll('.pt-tile').length===49,'49 board tiles');
  check(document.querySelectorAll('.pt-card').length===6,'six private cards');
  await click('.pt-suggestions button:nth-child(2)');
  check(document.querySelectorAll('.pt-card.selected').length===3,'valid three-card payment selected');
  await click('.pt-modes button:first-child');
  await click('.pt-tile[aria-label^="D1 "]');
  check(document.querySelector('.pt-modes button:first-child').disabled,'one move per activation');
  await button('Enemy 1',document.querySelector('.pt-targets'));
  await button('Confirm Impact');
  check(document.querySelector('.pt-unit.selected b').textContent==='Unit B','advance to next ready character');
  check(document.querySelector('.pt-tile[aria-label*="Enemy 1"]').textContent.includes('6 HP'),'three-card Impact deals 4 damage');
  await click('.pt-tile[aria-label^="E4 "]');
  await click('.pt-suggestions button:nth-child(3)');
  await button('Enemy 1',document.querySelector('.pt-targets'));
  await button('Confirm Control');
  check(document.querySelector('.pt-tile[aria-label*="Enemy 1"]').textContent.includes('NO MOVE'),'Control applies visible movement stop');
  check(document.querySelector('.pt-unit.selected b').textContent==='Unit C','support activation becomes ready');
  await click('.pt-card');
  await button('Exchange 1 selected cards');
  await button('Resolve enemy phase');
  check(document.querySelector('.pt-toolbar>strong').textContent==='Round 2','enemy phase resolves and starts next round');
  check(document.querySelectorAll('.pt-card').length===6,'refill to six cards');
  let captured;
  const original=HTMLAnchorElement.prototype.click;
  HTMLAnchorElement.prototype.click=function(){captured={url:this.href,name:this.download};};
  let session;
  try{await button('Export session');session=await(await fetch(captured.url)).json();}finally{HTMLAnchorElement.prototype.click=original;}
  const all=[...session.drawPile,...session.discard,...session.units.flatMap(u=>u.hand)];
  check(all.length===52&&new Set(all.map(c=>c.id)).size===52,'downloaded session preserves all 52 physical cards');
  check(session.events.filter(e=>e.type==='ability').length===2,'session contains paid-ability records');
  check(session.events.some(e=>e.type==='recover'),'session includes exchange decision');
  await button('End round early');
  check(!!document.querySelector('.pt-confirm'),'early end asks about unused actions');
  await button('Keep playing');
  location.hash='analysis';await new Promise(r=>setTimeout(r,1500));
  check(document.querySelectorAll('.details tbody tr').length===49,'probability explorer still works');
  location.hash='playtest';await pause();
  check(document.querySelector('.pt-toolbar>strong').textContent==='Round 2','encounter survives workspace tab changes');
  await button('Restart seed');
  check(document.querySelector('.pt-toolbar>strong').textContent==='Round 1','reproducible restart');
  return {messages,sessionFile:captured.name,roundTwo:{draw:session.drawPile.length,discard:session.discard.length,held:session.units.reduce((n,u)=>n+u.hand.length,0)}};
}
